const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const context=vm.createContext({module:{exports:{}}});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../dashboard/frontend/risk-details.js'),'utf8'),context);
const risk=context.module.exports;
for(const [score,key] of [[0,'low'],[59,'low'],[60,'medium'],[89,'medium'],[90,'high'],[119,'high'],[120,'critical'],[135,'critical'],[null,'unknown'],['','unknown'],['bad','unknown']]) assert.equal(risk.priority(score).key,key);
const anchor={time:'2026-10-10T17:40:27.052354+09:00',src_ip:'198.51.100.20',dst_ip:'192.0.2.10',user:'analyst',event:'AUTH_FAILURE',mitre:'T1110'};
const candidate={...anchor,time:'2026-10-10T17:41:27.052354+09:00'};
const raw=['same_src:+30','same_dst:+20','same_user:+20','time_5m:+30','same_mitre:+15','suspicious:+20'];
const reasons=risk.reasons(raw,anchor,candidate);
assert.equal(reasons.reduce((s,r)=>s+r.points,0),135);
assert.ok(reasons[0].description.includes('198.51.100.20'));
assert.ok(reasons[3].description.includes('1분 0초'));
assert.ok(risk.reasonHtml(raw,anchor,candidate).includes('합계 135점'));
assert.ok(risk.reasonHtml(raw,anchor,candidate).includes('같은 출발지 IP'));
assert.ok(risk.reasonHtml(['new_rule:+5'],anchor,candidate).includes('추가 규칙'));
assert.ok(risk.reasonHtml([],anchor,candidate).includes('제공되지 않았습니다'));
const malicious=risk.reasonHtml(['same_user:+20'],anchor,{...candidate,user:'<img src=x onerror=alert(1)>'});
assert.ok(!malicious.includes('<img'));
assert.ok(malicious.includes('&lt;img'));
assert.ok(risk.scoreBadge(135).includes('CRITICAL'));
console.log('Priority boundaries, additive explanations and escaping checks passed');
const html=fs.readFileSync(path.join(__dirname,'../dashboard/frontend/rsyslog.html'),'utf8');
for(const key of ['all','critical','high','medium','low']) assert.ok(html.includes(`<option value="${key}">`),`Missing priority option: ${key}`);
